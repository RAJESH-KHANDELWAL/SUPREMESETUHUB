def list_google_offerings() -> list[dict[str, Any]]:
    """Return the 129-source Google product inventory with Core routing."""
    results = []
    for product in GoogleEcosystemService().catalog():
        item = dict(product)
        family = EXACT.get(product["id"]) or CATEGORY.get(product.get("category", ""))
        item["core_family_id"] = family
        item["core_mapping_status"] = (
            "MAPPED_TO_CORE_FAMILY" if family else "SPECIALIZED_FAMILY_REVIEW_REQUIRED"
        )
        item["api_available"] = product.get("integration_mode") not in {"PRODUCT_INFORMATION_ONLY", "SDK_INTEGRATION"} and product.get("availability") != "DISCONTINUED"
        results.append(item)
    return results


def google_offerings_summary() -> dict[str, Any]:
    offerings = list_google_offerings()
    mapped = [item for item in offerings if item["core_family_id"]]
    unmapped = [item for item in offerings if not item["core_family_id"]]
    return {
        "success": True,
        "offering_count": len(offerings),
        "mapped_count": len(mapped),
        "specialized_review_count": len(unmapped),
        "product_information_only_count": sum(not item["api_available"] for item in offerings),
        "offerings": offerings,
        "specialized_review": [
            {"id": item["id"], "name": item["name"], "category": item["category"]}
            for item in unmapped
        ],
        "note": "A catalog listing does not imply a supported public API or a live integration.",
    }
