def list_language_records(language_type: str | None = None, *, search: str | None = None) -> list[dict[str, Any]]:
    records = LANGUAGE_RECORDS
    if language_type:
        records = tuple(row for row in records if row["language_type"].casefold() == language_type.strip().casefold())
    if search:
        needle = search.strip().casefold()
        records = tuple(row for row in records if needle in row["language_id"].casefold() or needle in row["canonical_name"].casefold() or needle in row["scope"].casefold() or any(needle in alias.casefold() for alias in row.get("aliases", ())))
    return deepcopy([dict(row) for row in records])
def get_language_record(language_id_or_name: str) -> dict[str, Any] | None:
    needle = language_id_or_name.strip().casefold()
    for row in LANGUAGE_RECORDS:
        names = [row["language_id"], row["canonical_name"], *row.get("aliases", ())]
        if needle in {name.casefold() for name in names}: return deepcopy(dict(row))
    return None
def language_catalog_summary() -> dict[str, Any]:
    from collections import Counter
    counts = Counter(row["language_type"] for row in LANGUAGE_RECORDS)
    return {"record_count":len(LANGUAGE_RECORDS),"type_counts":dict(sorted(counts.items())),"coverage_exhaustive":False,"catalog_scope":"curated languages, families, dialects, DSLs, markup, query, configuration, build, shell, hardware, proof and serialization"}
