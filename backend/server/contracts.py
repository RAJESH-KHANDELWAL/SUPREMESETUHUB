"""Contracts for SERVER-owned adapters; implementation stays in each domain."""
from typing import Any, Protocol, runtime_checkable

@runtime_checkable
class ServerRepositoryContract(Protocol):
    def create(self, record: dict[str, Any]) -> dict[str, Any]: ...
    def get(self, server_id: str) -> dict[str, Any] | None: ...
    def list(self) -> list[dict[str, Any]]: ...

@runtime_checkable
class ServerProviderContract(Protocol):
    provider_id: str
    def describe(self) -> dict[str, Any]: ...
    def health(self) -> dict[str, Any]: ...

@runtime_checkable
class ServerLifecycleContract(Protocol):
    def start(self, server_id: str) -> dict[str, Any]: ...
    def stop(self, server_id: str) -> dict[str, Any]: ...
