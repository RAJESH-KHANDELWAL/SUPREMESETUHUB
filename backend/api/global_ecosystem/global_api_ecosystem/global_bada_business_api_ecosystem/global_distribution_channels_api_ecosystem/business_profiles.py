def get_business_profile(channel_id: str):
    """Return a defensive copy of one channel's business profile."""
    profile = CHANNEL_BUSINESS_PROFILES.get(channel_id)
    if profile is None:
        return None
    return {key: list(value) if isinstance(value, list) else value for key, value in profile.items()}

def list_business_profiles():
    """Return defensive copies of all channel business profiles."""
    return {channel_id: get_business_profile(channel_id) for channel_id in CHANNEL_BUSINESS_PROFILES}
