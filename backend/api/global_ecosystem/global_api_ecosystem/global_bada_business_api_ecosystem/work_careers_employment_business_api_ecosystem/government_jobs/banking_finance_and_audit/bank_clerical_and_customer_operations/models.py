"""Domain model for Public bank clerical and customer operations."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    bank_clerical_grade: str
    bank_or_branch: str
    customer_or_cash_function: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "branch_service_and_transactions"
