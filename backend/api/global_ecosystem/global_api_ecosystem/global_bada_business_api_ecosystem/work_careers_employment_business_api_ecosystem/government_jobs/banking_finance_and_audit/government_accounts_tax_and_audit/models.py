"""Domain model for Government accounts, taxation and audit posts."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    accounts_or_audit_grade: str
    department_or_audit_body: str
    finance_specialism: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "public_finance_and_compliance"
