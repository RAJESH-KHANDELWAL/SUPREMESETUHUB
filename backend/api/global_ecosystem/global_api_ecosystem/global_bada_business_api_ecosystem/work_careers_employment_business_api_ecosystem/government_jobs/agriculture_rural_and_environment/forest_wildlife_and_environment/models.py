"""Domain model for Forest, wildlife and environmental posts."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    environmental_service_rank: str
    forest_or_environment_circle: str
    conservation_specialism: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "conservation_and_enforcement"
