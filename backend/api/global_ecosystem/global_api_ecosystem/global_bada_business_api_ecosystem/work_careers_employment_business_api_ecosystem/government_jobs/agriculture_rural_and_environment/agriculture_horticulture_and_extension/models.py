"""Domain model for Agriculture, horticulture and extension posts."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    agriculture_grade: str
    agriculture_department: str
    crop_or_extension_specialism: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "farm_advisory_and_extension"
