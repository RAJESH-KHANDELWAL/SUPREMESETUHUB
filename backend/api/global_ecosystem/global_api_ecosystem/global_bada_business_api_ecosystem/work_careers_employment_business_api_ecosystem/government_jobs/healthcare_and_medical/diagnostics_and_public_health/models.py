"""Domain model for Diagnostic and public health posts."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    technical_health_grade: str
    diagnostic_or_public_health: str
    lab_or_field_unit: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "diagnostics_and_population_health"
