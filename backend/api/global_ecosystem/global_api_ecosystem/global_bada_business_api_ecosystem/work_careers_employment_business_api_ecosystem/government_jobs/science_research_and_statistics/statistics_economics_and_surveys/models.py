"""Domain model for Statistics, economics and survey posts."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    analytical_grade: str
    statistics_or_economic_unit: str
    quantitative_discipline: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "official_statistics_and_policy_analysis"
