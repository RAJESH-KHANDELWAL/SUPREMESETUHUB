"""Domain model for Prison, forensic and intelligence support posts."""
from dataclasses import dataclass
from typing import Optional

@dataclass(frozen=True)
class GovernmentPost:
    post_id: str
    post_title: str
    recruiting_authority: str
    specialist_safety_grade: str
    prison_forensic_or_intelligence: str
    facility_or_lab: str
    employment_status: str = "notices_to_be_verified"
    notification_reference: Optional[str] = None
    official_notice_url: Optional[str] = None

    @property
    def work_function(self) -> str:
        return "custody_evidence_and_intelligence_support"
