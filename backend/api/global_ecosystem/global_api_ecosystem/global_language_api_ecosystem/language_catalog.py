def list_languages(query: str | None = None, limit: int = 250) -> list[dict[str, str]]:
    """Return the curated world-language catalog with optional case-insensitive filtering."""
    needle = (query or "").strip().casefold()
    cap = max(1, min(int(limit), 500))
    rows = [dict(item) for item in WORLD_LANGUAGES if not needle or needle in item["id"].casefold() or needle in item["name"].casefold() or needle in item["family"].casefold()]
    return rows[:cap]

def list_locales(language: str | None = None, limit: int = 250) -> list[dict[str, str]]:
    """Return locale/region variants, optionally filtered by ISO-like language identifier."""
    needle = (language or "").strip().casefold()
    cap = max(1, min(int(limit), 500))
    rows = [dict(item) for item in LOCALES if not needle or item["language"].casefold() == needle or item["id"].casefold().startswith(needle + "-")]
    return rows[:cap]

