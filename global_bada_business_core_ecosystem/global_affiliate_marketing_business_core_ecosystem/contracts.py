"""Provider-neutral contracts for affiliate CORE persistence boundaries."""
from __future__ import annotations

from typing import Any, Protocol

class AffiliateRepository(Protocol):
    """Persistence contract implemented by the DATABASE layer."""

    def upsert_program(self, **record: Any) -> dict[str, Any]: ...
    def list_programs(self, platform_id: str | None = None) -> list[dict[str, Any]]: ...
    def get_program(self, program_id: str) -> dict[str, Any] | None: ...
    def create_referral(self, **record: Any) -> dict[str, Any]: ...
    def get_referral(self, referral_id: str) -> dict[str, Any] | None: ...
    def record_event(self, **record: Any) -> dict[str, Any]: ...

__all__ = ["AffiliateRepository"]
